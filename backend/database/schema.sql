-- Reconstructed schema for a NEW, empty demo database only. No DROP statements.
CREATE TABLE IF NOT EXISTS Users (
 user_id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 role VARCHAR(30) NOT NULL DEFAULT 'participant', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS Categories (
 category_id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255) NOT NULL UNIQUE, description TEXT
);
CREATE TABLE IF NOT EXISTS Posts (
 post_id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, category_id INT,
 title VARCHAR(255) NOT NULL, content TEXT NOT NULL, likes INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
 FOREIGN KEY(category_id) REFERENCES Categories(category_id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS Comments (
 comment_id INT AUTO_INCREMENT PRIMARY KEY, post_id INT NOT NULL, user_id INT NOT NULL,
 comment TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(post_id) REFERENCES Posts(post_id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES Users(user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS PostLikes (
 post_id INT NOT NULL, user_id INT NOT NULL, PRIMARY KEY(post_id,user_id),
 FOREIGN KEY(post_id) REFERENCES Posts(post_id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES Users(user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Resources (
 resource_id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255) NOT NULL, description TEXT NOT NULL,
 category_id INT, file_url VARCHAR(512) NOT NULL, uploaded_by INT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES Categories(category_id) ON DELETE SET NULL,
 FOREIGN KEY(uploaded_by) REFERENCES Users(user_id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS Notifications (
 notification_id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, type VARCHAR(30) NOT NULL,
 message TEXT NOT NULL, related_id INT, is_read BOOLEAN DEFAULT FALSE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES Users(user_id) ON DELETE CASCADE
);
